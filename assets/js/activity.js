/* Live GitHub activity for the landing build-log panel.
   Merges two sources:
   - GitHub public events API (public repos, with commit messages)
   - /assets/data/activity.json (local scan of private repos: names + counts only,
     regenerated by scripts/update-activity.mjs on publish)
   No dependencies. Fails quietly to a static link if both sources are unreachable. */
(function () {
  var USER = 'dontoisme';
  var feed = document.querySelector('[data-activity-feed]');
  if (!feed) return;
  var statEl = document.querySelector('[data-activity-stat]');
  var MAX_ROWS = 8;
  var MAX_LOCAL_ROWS_PER_REPO = 3;

  function rel(iso) {
    var s = (Date.now() - new Date(iso).getTime()) / 1000;
    if (s < 90) return 'now';
    var m = s / 60; if (m < 60) return Math.round(m) + 'm';
    var h = m / 60; if (h < 24) return Math.round(h) + 'h';
    var d = h / 24; if (d < 7) return Math.round(d) + 'd';
    var w = d / 7; if (w < 5) return Math.round(w) + 'w';
    return Math.round(d / 30) + 'mo';
  }
  function esc(t) { var e = document.createElement('span'); e.textContent = (t == null ? '' : t); return e.innerHTML; }
  function firstLine(t) { return (t || '').split('\n')[0]; }
  function shortRepo(full) { return full.split('/').slice(-1)[0]; }
  function dayOf(iso) { return iso.slice(0, 10); }

  function describe(ev) {
    var p = ev.payload || {};
    switch (ev.type) {
      case 'PushEvent':
        var c = (p.commits && p.commits.length) || 0;
        var msg = c ? firstLine(p.commits[p.commits.length - 1].message) : '';
        return { verb: 'push', extra: c > 1 ? c + ' commits' : '', detail: msg };
      case 'PullRequestEvent':
        return { verb: 'PR ' + (p.action || ''), extra: '', detail: p.pull_request && p.pull_request.title };
      case 'CreateEvent':
        return { verb: 'create', extra: '', detail: (p.ref_type || '') + (p.ref ? ' ' + p.ref : '') };
      case 'ReleaseEvent':
        return { verb: 'release', extra: '', detail: p.release && p.release.tag_name };
      case 'IssuesEvent':
        return { verb: 'issue ' + (p.action || ''), extra: '', detail: p.issue && p.issue.title };
      default:
        return null;
    }
  }

  function publicRow(ev, d) {
    var li = document.createElement('li');
    li.className = 'buildlog-row';
    li.innerHTML =
      '<span class="bl-time">' + esc(rel(ev.created_at)) + '</span>' +
      '<span class="bl-verb">' + esc(d.verb) + '</span>' +
      '<a class="bl-repo" href="https://github.com/' + esc(ev.repo.name) + '">' + esc(shortRepo(ev.repo.name)) + '</a>' +
      (d.extra ? '<span class="bl-extra">' + esc(d.extra) + '</span>' : '') +
      (d.detail ? '<span class="bl-detail">' + esc(d.detail) + '</span>' : '');
    return li;
  }

  function localRow(entry) {
    var li = document.createElement('li');
    li.className = 'buildlog-row is-local';
    li.innerHTML =
      '<span class="bl-time">' + esc(rel(entry.last)) + '</span>' +
      '<span class="bl-verb">push</span>' +
      '<span class="bl-repo">' + esc(entry.repo) + '</span>' +
      '<span class="bl-extra">' + entry.n + ' commit' + (entry.n !== 1 ? 's' : '') + '</span>';
    return li;
  }

  function markActive(names) {
    document.querySelectorAll('[data-repo]').forEach(function (card) {
      if (names[card.getAttribute('data-repo')]) {
        card.classList.add('is-active');
        var b = card.querySelector('[data-active-badge]');
        if (b) b.hidden = false;
      }
    });
  }

  function fallback() {
    feed.innerHTML = '<li class="buildlog-row buildlog-fallback"><span class="bl-detail">Live feed unavailable — ' +
      '<a href="https://github.com/' + USER + '?tab=overview">see activity on GitHub ↗</a></span></li>';
  }

  function fetchJSON(url) {
    return fetch(url).then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); });
  }

  var base = (document.currentScript && document.currentScript.src)
    ? document.currentScript.src.replace(/js\/activity\.js.*$/, '')
    : '/assets/';

  Promise.allSettled([
    fetchJSON('https://api.github.com/users/' + USER + '/events/public?per_page=60'),
    fetchJSON(base + 'data/activity.json')
  ]).then(function (results) {
    var events = results[0].status === 'fulfilled' ? results[0].value : [];
    var local = results[1].status === 'fulfilled' ? results[1].value : { repos: [] };

    var rows = [];              // { time, li }
    var covered = {};           // 'repo|YYYY-MM-DD' -> true, from public pushes
    var weekCommits = {};       // 'repo|YYYY-MM-DD' -> count (last 7 days)
    var activeNames = {};
    var weekAgo = Date.now() - 7 * 864e5;

    events.forEach(function (ev, i) {
      var name = shortRepo(ev.repo.name);
      if (ev.type === 'PushEvent') covered[name.toLowerCase() + '|' + dayOf(ev.created_at)] = true;
      if (i < 30) activeNames[name.toLowerCase()] = true;
      if (ev.type === 'PushEvent' && new Date(ev.created_at).getTime() >= weekAgo) {
        var k = name.toLowerCase() + '|' + dayOf(ev.created_at);
        weekCommits[k] = (weekCommits[k] || 0) + ((ev.payload.commits && ev.payload.commits.length) || 1);
      }
      var d = describe(ev);
      if (d) rows.push({ time: new Date(ev.created_at).getTime(), li: publicRow(ev, d) });
    });

    (local.repos || []).forEach(function (r) {
      var shown = 0;
      (r.days || []).forEach(function (day) {
        var k = r.name.toLowerCase() + '|' + day.d;
        if (new Date(day.last).getTime() >= weekAgo) {
          // Local counts are exact; take the max so public push events aren't double-counted.
          weekCommits[k] = Math.max(weekCommits[k] || 0, day.n);
          activeNames[r.name.toLowerCase()] = true;
        }
        if (covered[k] || shown >= MAX_LOCAL_ROWS_PER_REPO) return;
        rows.push({ time: new Date(day.last).getTime(), li: localRow({ repo: r.name, n: day.n, last: day.last }) });
        shown++;
      });
    });

    if (!rows.length) { fallback(); return; }
    rows.sort(function (a, b) { return b.time - a.time; });
    feed.innerHTML = '';
    rows.slice(0, MAX_ROWS).forEach(function (r) { feed.appendChild(r.li); });

    if (statEl) {
      var commits = 0, repoSet = {};
      Object.keys(weekCommits).forEach(function (k) {
        commits += weekCommits[k];
        repoSet[k.split('|')[0]] = true;
      });
      var n = Object.keys(repoSet).length;
      if (n) statEl.textContent = commits + ' commit' + (commits !== 1 ? 's' : '') + ' · ' + n + ' repo' + (n !== 1 ? 's' : '') + ' · last 7 days';
    }
    markActive(activeNames);
  }).catch(fallback);
})();
